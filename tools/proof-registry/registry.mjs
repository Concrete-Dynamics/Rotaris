/**
 * The proof registry — one machine-readable record per proof entry, and the source of the human index.
 *
 * `AGENTS.md` keeps the proof *rules*: a proof launches the **built** application against a scratch profile and
 * measures a mechanism in the product; run the whole suite a part touches, not the one script named after it; and a
 * red is a defect of the product until the harness is shown to be wrong. This registry answers *which* proof covers
 * what, so an agent can plan verification without reading forty script headers: the area an entry belongs to, the
 * neighbouring proofs that share a mechanism with it, what it needs beyond the standard harness (a built
 * application, a scratch profile and a display), the hosts it runs to its end on with the per-host clauses
 * beside them, and the flags a runner passes it.
 *
 * It renders `docs/proofs/README.md` — the human index — through `node tools/proof-registry/generate.mjs --write`,
 * which `pnpm proofs:index` runs and `pnpm lint` re-checks. The full record of what an entry measures, the part
 * that grows as the work lands, is the document its id names under `docs/proofs/`; a summary here is one line and
 * never the whole story.
 *
 * The guard beside this file (`registry.test.ts`) holds the registry to the tree: every `*-proof.mjs`,
 * `live-run`, `ui-audit` and `ui-review` script has exactly one record and no record names a script that is not
 * there; every id is the pnpm script that runs it; every record opens with its id; every neighbour resolves and
 * the relation is symmetric; every recorded flag is one the script reads, and every flag the script reads from
 * its own argv (`flags.mjs`) is recorded, so a flag cannot hide in the script or dangle in the column. The
 * rendered index's freshness is `pnpm lint`'s check (`generate.mjs --check`), not the guard's.
 *
 * Entry fields:
 *   id             the pnpm script name, the script's basename and the record's basename
 *   area           one of `AREAS`, the grouping the index renders
 *   summary        one line: what the proof measures
 *   neighbours     ids of the proofs sharing a mechanism with this one, and therefore most likely to break with it
 *   requires       what it needs beyond the standard harness (usually nothing)
 *   platforms      the hosts it runs to its end on
 *   platformNotes  per-host clauses: a check asserted on one host, a reading cold on one platform only
 *   flags          the flags a runner may pass it, in the shell-shaped form the index prints
 */

